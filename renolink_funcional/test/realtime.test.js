'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const {once}=require('node:events');
const {fixture}=require('./fixtures/mysql');
const {seed}=require('./fixtures/phase5');
const {initialize}=require('../lib/phase5-data');
const {validate}=require('../lib/data');
const security=require('../lib/security');
const {createServer}=require('../server');
const {subscribe,waitFor,sleep}=require('./fixtures/events');
function memoryStore(db){let value=structuredClone(db),queue=Promise.resolve();return{transaction(fn){const next=queue.then(async()=>{const copy=structuredClone(value);const result=await fn(copy);validate(copy);value=copy;return result;});queue=next.catch(()=>{});return next;}};}
test('SSE: autenticacao, isolamento, replay, limites, revogacao e ausencia de eventos em falhas',async t=>{
 const db=initialize(fixture()),ids=seed(db),store=memoryStore(db);
 const cookie=async id=>(await store.transaction(state=>security.issueSession({userId:id},state).cookie)).split(';')[0];
 const cookies={a:await cookie(ids.visitor),b:await cookie(ids.outsider),admin:await cookie(ids.admin)};
 const server=createServer(store,{realtime:{pollIntervalMs:40,heartbeatMs:1000,historyLimit:20}});server.listen(0,'127.0.0.1');await once(server,'listening');
 const base=`http://127.0.0.1:${server.address().port}`,streams=[];
 t.after(async()=>{for(const stream of streams)await stream.close();await new Promise(resolve=>server.close(resolve));});
 const request=async(route,data,session)=>{const r=await fetch(base+route,{method:data===undefined?'GET':'POST',headers:{'Content-Type':'application/json',...(session?{Cookie:session}:{})},body:data===undefined?undefined:JSON.stringify(data)});return{status:r.status,body:await r.json()};};
 assert.equal((await request('/api/events')).status,401);
 assert.equal((await fetch(base+'/api/events',{headers:{Cookie:cookies.a,Origin:'http://outsider.invalid'}})).status,403);
 assert.equal((await fetch(base+'/api/events',{headers:{Cookie:cookies.a,'Last-Event-ID':'invalid'}})).status,400);
 for(const key of ['a','b','admin']){const stream=await subscribe(base,cookies[key]);streams.push(stream);cookies[key+'Stream']=stream;await stream.wait(e=>e.type==='ready');}
 const a=cookies.aStream,b=cookies.bStream,admin=cookies.adminStream;
 let idea=(await request('/api/ideas',{title:'Ideia privada SSE',category:'Tecnologia',problem:'Problema',solution:'Solucao'},cookies.a)).body.idea;
 await a.wait(e=>e.type==='changes'&&e.data.topics.includes('ideas'));await admin.wait(e=>e.type==='changes'&&e.data.topics.includes('ideas'));
 await sleep(160);assert.equal(b.events.filter(e=>e.type==='changes').length,0);
 const count=admin.events.length;assert.equal((await request('/api/ideas',{title:'Incompleta'},cookies.a)).status,400);await sleep(160);assert.equal(admin.events.length,count);
 const conversation=(await request('/api/team/conversations',{text:'Mensagem privada SSE'},cookies.a)).body.conversation;
 await a.wait(e=>e.type==='changes'&&e.data.topics.includes('messages'));await admin.wait(e=>e.type==='changes'&&e.data.topics.includes('messages'));
 await sleep(120);assert.equal(b.events.filter(e=>e.type==='changes').length,0);
 assert.ok(!JSON.stringify([...a.events,...admin.events]).includes('Mensagem privada SSE'));
 assert.ok(a.events.every(e=>!e.data.topics?.includes('audit')&&!e.data.topics?.includes('users')));
 const last=a.events.filter(e=>e.id).at(-1).id;await a.close();
 await request(`/api/admin/conversations/${conversation.id}/messages`,{text:'Resposta privada SSE'},cookies.admin);
 const resumed=await subscribe(base,cookies.a,last);streams.push(resumed);
 await resumed.wait(e=>e.type==='changes'&&e.data.topics.includes('messages'));
 const replayIds=resumed.events.filter(e=>e.id).map(e=>e.id);assert.equal(new Set(replayIds).size,replayIds.length);
 assert.ok(!JSON.stringify(resumed.events).includes('Resposta privada SSE'));
 const foreign=b.events.find(e=>e.id).id;
 const foreignResume=await subscribe(base,cookies.a,foreign);streams.push(foreignResume);await foreignResume.wait(e=>e.type==='reset');
 assert.ok(foreignResume.events.every(e=>!e.data.topics?.includes('audit')));
 const extra=await subscribe(base,cookies.a);streams.push(extra);await extra.wait(e=>e.type==='ready');
 assert.equal((await request('/api/events',undefined,cookies.a)).status,429);await extra.close();await foreignResume.close();
 const reviewed=await request(`/api/admin/ideas/${idea.id}/review`,{decision:'approve',updatedAt:idea.updatedAt},cookies.admin);assert.equal(reviewed.status,200);idea=reviewed.body.idea;
 await b.wait(e=>e.type==='changes'&&e.data.topics.includes('ideas'));
 const beforeDeals=b.events.filter(e=>e.type==='changes'&&e.data.topics.includes('deals')).length;
 assert.equal((await request('/api/requests',{ideaId:idea.id},cookies.a)).status,201);
 await resumed.wait(e=>e.type==='changes'&&e.data.topics.includes('deals'));await admin.wait(e=>e.type==='changes'&&e.data.topics.includes('deals'));
 await sleep(120);assert.equal(b.events.filter(e=>e.type==='changes'&&e.data.topics.includes('deals')).length,beforeDeals);
 await store.transaction(state=>{state.staff.find(s=>s.userId===ids.admin).active=0;});
 await admin.wait(e=>e.type==='access-changed');await waitFor(()=>admin.ended());
 await store.transaction(state=>{for(const s of state.sessions.filter(s=>s.userId===ids.visitor))s.revokedAt=new Date().toISOString();});
 await resumed.wait(e=>e.type==='session-expired');await waitFor(()=>resumed.ended());
});
