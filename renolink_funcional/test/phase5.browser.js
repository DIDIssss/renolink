'use strict';
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { once } = require('node:events');
const mysql = require('../lib/mysql');
const { createServer } = require('../server');
const { seed } = require('./fixtures/phase5');
const root = path.resolve(__dirname, '..');
async function main() {
  assert.equal(process.env.RENOLINK_PHASE5_TEST_APPROVED, '1');
  const options = mysql.config(process.env, 'TEST_MYSQL_');
  assert.equal(options.database, 'renolink_test'); assert.equal(options.user, 'renolink_tester');
  const store = mysql.mysqlStore(options);
  const ids = await store.transaction(db => { assert.equal(db.meta.schemaVersion,5); return seed(db); });
  const server = createServer(store); server.listen(0,'127.0.0.1'); await once(server,'listening');
  const base = `http://127.0.0.1:${server.address().port}`;
  const output = path.join(root, 'data/runtime/phase5-preview'); fs.mkdirSync(output,{recursive:true});
  const browser = await chromium.launch({ channel:'chrome', headless:true });
  const errors = [], dialogs = [];
  const checks = [];
  try {
    const desktop = await browser.newContext({ viewport:{width:1440,height:1000}, locale:'pt-BR' });
    const mobile = await browser.newContext({ viewport:{width:390,height:844}, isMobile:true, hasTouch:true, locale:'pt-BR' });
    const admin = await desktop.newPage(), visitor = await mobile.newPage();
    for (const page of [admin,visitor]) { page.on('pageerror',e=>errors.push(e.message)); page.on('dialog',async d=>{dialogs.push(d.message());await d.dismiss();}); }
    await admin.goto(base + '/admin-login.html');
    await admin.locator('#adminEmail').fill(ids.adminEmail); await admin.locator('#adminPassword').fill('SenhaTeste2026!');
    await admin.getByRole('button',{name:'Entrar no painel'}).click(); await admin.waitForURL('**/admin.html');
    await admin.locator('.team-metric').first().waitFor();
    await admin.screenshot({path:path.join(output,'admin-desktop.png'),fullPage:true});
    checks.push('login administrativo e dashboard desktop real');
    const signupEmail = `signup-${ids.visitor}@teste.invalid`;
    await visitor.goto(base + '/cadastro.html');
    await visitor.locator('#nome').fill('Visitante de teste'); await visitor.locator('#email').fill(signupEmail);
    await visitor.locator('#senha').fill('SenhaTeste2026!'); await visitor.locator('#cadastroForm button[type=submit]').click();
    await visitor.waitForURL('**/dashboard.html');
    await visitor.locator('.visitor-mobile-nav').getByRole('button',{name:'Sair',exact:true}).click(); await visitor.waitForURL('**/index.html');
    await visitor.goto(base + '/login.html');
    await visitor.locator('input[name=email]').fill(signupEmail); await visitor.locator('input[name=password]').fill('SenhaTeste2026!');
    await visitor.locator('#loginForm button[type=submit]').click(); await visitor.waitForURL('**/dashboard.html');
    await visitor.locator('#userName').filter({hasText:'Visitante de teste'}).waitFor();
    const visitorId = (await (await mobile.request.get(base + '/api/me')).json()).user.id;
    checks.push('cadastro publico, logout e login pelo formulario mobile');
    await visitor.locator('.visitor-mobile-nav').getByRole('link',{name:'Nova ideia',exact:true}).click();
    const title = `Ideia navegador ${ids.visitor}`;
    await visitor.locator('#titulo').fill(title); await visitor.locator('#categoria').selectOption('Tecnologia');
    await visitor.locator('#problema').fill('Visitantes precisam de uma experiência acessível na feira.'); await visitor.locator('#solucao').fill('Uma plataforma de atendimento próxima e inclusiva.');
    await visitor.locator('#ideaForm button[type=submit]').click(); await visitor.waitForURL('**/dashboard.html?created=1');
    await visitor.getByRole('link',{name:title,exact:true}).click(); await visitor.getByRole('link',{name:'Editar minha ideia'}).click();
    await visitor.locator('#ideaForm button[type=submit]').waitFor({state:'visible'});
    await visitor.waitForFunction(()=>!document.querySelector('#ideaForm button[type=submit]').disabled);
    await visitor.locator('#solucao').fill('Uma proposta revisada, inclusiva e acessível.');
    await visitor.locator('#ideaForm button[type=submit]').click(); await visitor.waitForURL('**/dashboard.html?created=1');
    checks.push('cadastro e edicao de ideia propria no celular');
    await admin.getByRole('button',{name:'Ideias recebidas',exact:true}).click(); await admin.locator('#adminSearch').fill(title);
    await admin.locator('#ideaRows').getByRole('button',{name:'Analisar',exact:true}).click();
    await admin.locator('#reviewReason').fill('Proposta aprovada para a demonstração.'); await admin.locator('#approveIdea').click(); await admin.locator('#ideaDialog').waitFor({state:'hidden'});
    await visitor.reload(); await visitor.getByRole('link',{name:title,exact:true}).click();
    await visitor.locator('#interestButton').click(); await visitor.locator('#interestAlert').filter({hasText:'Solicitação enviada'}).waitFor();
    await visitor.locator('.visitor-mobile-nav').getByRole('link',{name:'Negociações',exact:true}).click();
    await visitor.locator('#negotiationList').getByText('Solicitada',{exact:true}).waitFor();
    await admin.getByRole('button',{name:'Negociações',exact:true}).click();
    const row = admin.getByRole('row').filter({hasText:title}); await row.getByRole('combobox').selectOption('Em contato'); await row.getByRole('button',{name:'Atualizar etapa'}).click();
    await admin.locator('#adminNotice').filter({hasText:'Etapa atualizada'}).waitFor();
    await visitor.reload(); await visitor.getByText('Em contato',{exact:true}).waitFor();
    checks.push('aprovacao pelo painel e acompanhamento da negociacao');
    await visitor.locator('.visitor-mobile-nav').getByRole('link',{name:'Equipe',exact:true}).click();
    await visitor.waitForFunction(()=>!document.querySelector('#messageForm button').disabled);
    await visitor.locator('#messageText').fill('Olá, gostaria de conversar com a equipe sobre a ideia.'); await visitor.locator('#messageForm button').click();
    await visitor.locator('#messageList').getByText('Olá, gostaria de conversar com a equipe sobre a ideia.').waitFor();
    const conversationId = await store.transaction(db=>db.conversations.find(c=>c.visitorId === visitorId).id);
    await admin.getByRole('button',{name:'Atendimento',exact:true}).click(); await admin.locator(`[data-conversation="${conversationId}"]`).click();
    await admin.locator('#replyText').fill('Recebemos sua proposta. Vamos conversar!'); await admin.locator('#replyForm button').click();
    await admin.locator('#teamChat').getByText('Recebemos sua proposta. Vamos conversar!').waitFor();
    await visitor.locator('#refreshMessages').click(); await visitor.locator('#messageList').getByText('Recebemos sua proposta. Vamos conversar!').waitFor();
    await visitor.screenshot({path:path.join(output,'visitante-mobile.png'),fullPage:true});
    checks.push('conversa bidirecional visitante-equipe pelo navegador');
    await admin.setViewportSize({width:390,height:844}); await admin.locator('#teamMenu').click(); await admin.getByRole('button',{name:'Visão geral',exact:true}).click();
    await admin.locator('.team-metric').first().waitFor(); await admin.screenshot({path:path.join(output,'admin-mobile.png'),fullPage:true});
    for (const page of [admin,visitor]) assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth),true,'Sem rolagem horizontal da pagina no celular.');
    checks.push('menu mobile da equipe e do visitante, sem overflow horizontal');
    await visitor.goto(base + '/admin.html'); assert.ok(visitor.url().endsWith('/admin-login.html'));
    checks.push('visitante impedido de abrir o painel administrativo');
    assert.deepEqual(errors,[]); assert.deepEqual(dialogs,[]);
    fs.writeFileSync(path.join(root,'data/runtime/phase5-browser-report.json'),JSON.stringify({status:'passed',database:'renolink_test',browser:'Chrome headless',desktop:'1440x1000',mobile:'390x844',checks,pageErrors:errors,unexpectedDialogs:dialogs,screenshots:output,devSchemaApplied:false},null,2));
    console.log(JSON.stringify({status:'passed',checks,screenshots:output},null,2));
  } finally { await browser.close(); server.closeAllConnections(); await new Promise(resolve=>server.close(resolve)); await store.close(); }
}
main().catch(error=>{console.error('Teste de navegador interrompido:',error.message);process.exitCode=1;});
